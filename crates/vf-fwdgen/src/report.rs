//! What the generator says it did: a manifest per library (read back by `verify`), a summary on
//! standard output and the full report.

use crate::StatusDiff;
use crate::elf::Library;
use crate::libs::LibSpec;
use crate::plan::{Action, Entry, StubReason};
use std::fmt::Write;
use std::path::Path;

pub struct LibResult<'a> {
    pub spec: &'a LibSpec,
    pub target: String,
    pub entries: Vec<Entry>,
    pub diff: Option<StatusDiff>,
    pub new: Library,
    pub old: Library,
}

pub fn write_manifest(dir: &Path, entries: &[Entry]) -> Result<(), String> {
    let mut s = String::new();
    for e in entries {
        let (kind, target) = match &e.action {
            Action::Forward { target } => ("forward", target.as_str()),
            Action::ForwardStatus { target, .. } => ("forward-status", target.as_str()),
            Action::Stub { .. } => ("stub", "-"),
        };
        writeln!(
            s,
            "{}\t{}\t{}\t{}",
            e.name,
            kind,
            target,
            e.version.as_deref().unwrap_or("-")
        )
        .unwrap();
    }
    std::fs::write(dir.join("manifest.tsv"), s).map_err(|e| e.to_string())
}

#[derive(Default)]
pub struct Counts {
    pub exports: usize,
    pub forwarded: usize,
    pub renumbered: usize,
    pub adapted: usize,
    pub absent: usize,
    pub changed: usize,
}

pub fn counts(entries: &[Entry]) -> Counts {
    let mut c = Counts {
        exports: entries.len(),
        ..Counts::default()
    };
    for e in entries {
        if matches!(e.action, Action::ForwardStatus { .. }) {
            c.renumbered += 1;
        }
        match &e.action {
            Action::Stub {
                reason: StubReason::Absent,
                ..
            } => c.absent += 1,
            Action::Stub {
                reason: StubReason::SignatureChanged(..),
                ..
            } => c.changed += 1,
            _ if e.adapted.is_some() => c.adapted += 1,
            _ => c.forwarded += 1,
        }
    }
    c
}

pub fn summary(results: &[LibResult]) -> String {
    let mut s = String::new();
    writeln!(
        s,
        "{:<28} {:>7} {:>9} {:>9} {:>8} {:>8} {:>8}   serves",
        "library", "exports", "forwarded", "renumbered", "adapted", "absent", "changed"
    )
    .unwrap();
    let mut total = Counts::default();
    for r in results {
        let c = counts(&r.entries);
        writeln!(
            s,
            "{:<28} {:>7} {:>9} {:>9} {:>8} {:>8} {:>8}   {}",
            r.spec.new_name, c.exports, c.forwarded, c.renumbered, c.adapted, c.absent, c.changed, r.target
        )
        .unwrap();
        total.exports += c.exports;
        total.forwarded += c.forwarded;
        total.renumbered += c.renumbered;
        total.adapted += c.adapted;
        total.absent += c.absent;
        total.changed += c.changed;
    }
    writeln!(
        s,
        "{:<28} {:>7} {:>9} {:>9} {:>8} {:>8} {:>8}",
        "total", total.exports, total.forwarded, total.renumbered, total.adapted, total.absent, total.changed
    )
    .unwrap();
    s.push_str("(`renumbered` is a subset of forwarded + adapted: forwarded with the returned status renumbered)\n");
    s
}

pub fn render(results: &[LibResult]) -> String {
    let mut s = String::from("Forwarding libraries generated by vf-fwdgen\n\n");
    s.push_str(&summary(results));
    for r in results {
        let c = counts(&r.entries);
        writeln!(
            s,
            "\n== {}  (serves: {}, loaded by `{}`)",
            r.spec.new_name, r.spec.old_name, r.target
        )
        .unwrap();
        writeln!(
            s,
            "exports {} | forwarded {} | adapted {} | not supported {} (absent from 12.9: {}, prototype changed: {}) | status renumbered on return: {}",
            c.exports, c.forwarded, c.adapted, c.absent + c.changed, c.absent, c.changed, c.renumbered
        )
        .unwrap();
        writeln!(
            s,
            "exports only in the 12.9 library (not exported by 13.5, so not exported here): {}",
            only_old(r)
        )
        .unwrap();
        if let Some(d) = &r.diff {
            if d.renumbered.is_empty() {
                writeln!(
                    s,
                    "status type {}: no enumerator changed value; only in 12.9: [{}]; only in 13.5: [{}]",
                    r.spec.status.as_ref().unwrap().ty,
                    d.only_old.join(" "),
                    d.only_new.join(" ")
                )
                .unwrap();
            } else {
                writeln!(
                    s,
                    "status type {}: {} enumerators changed value, renumbered on return (12.9 -> 13.5):",
                    r.spec.status.as_ref().unwrap().ty,
                    d.renumbered.len()
                )
                .unwrap();
                for (n, o, w) in &d.renumbered {
                    writeln!(s, "    {n}: {o} -> {w}").unwrap();
                }
                writeln!(
                    s,
                    "  only in 12.9: {}; only in 13.5: {}",
                    d.only_old.join(" "),
                    d.only_new.join(" ")
                )
                .unwrap();
            }
        }
        let adapted: Vec<&Entry> = r.entries.iter().filter(|e| e.adapted.is_some()).collect();
        if !adapted.is_empty() {
            writeln!(s, "adapted ({}):", adapted.len()).unwrap();
            for e in adapted.iter().take(60) {
                let to = match &e.action {
                    Action::Forward { target } | Action::ForwardStatus { target, .. } => target.as_str(),
                    _ => "-",
                };
                writeln!(s, "    {} -> {}: {}", e.name, to, e.adapted.as_ref().unwrap()).unwrap();
            }
            if adapted.len() > 60 {
                writeln!(s, "    ... {} more of the same kind", adapted.len() - 60).unwrap();
            }
        }
        let stubs: Vec<&Entry> = r
            .entries
            .iter()
            .filter(|e| matches!(e.action, Action::Stub { .. }))
            .collect();
        if !stubs.is_empty() {
            writeln!(s, "not supported ({}): name [what the stub returns]", stubs.len()).unwrap();
            for e in stubs {
                let Action::Stub { ret, reason } = &e.action else {
                    continue;
                };
                let what = match (ret, r.spec.status.as_ref()) {
                    (crate::plan::Return::Status, Some(st)) => format!("status {}", st.not_supported),
                    (crate::plan::Return::Unknown, Some(st)) => {
                        format!("unknown type, taken for a status: {}", st.not_supported)
                    }
                    (crate::plan::Return::Unknown, None) => "unknown type: 0".to_string(),
                    (crate::plan::Return::Void, _) => "nothing".to_string(),
                    (ret, _) => format!("{}: 0", ret.name()),
                };
                match reason {
                    StubReason::Absent => writeln!(s, "    {} [{}]", e.name, what).unwrap(),
                    StubReason::SignatureChanged(a, b) => writeln!(
                        s,
                        "    {} [{}] prototype changed: 12.9 `{}`, 13.5 `{}`",
                        e.name, what, a, b
                    )
                    .unwrap(),
                }
            }
        }
    }
    s
}

fn only_old(r: &LibResult) -> usize {
    let new: std::collections::BTreeSet<&str> = r.new.exports.iter().map(|s| s.name.as_str()).collect();
    r.old.exports.iter().filter(|s| !new.contains(s.name.as_str())).count()
}
